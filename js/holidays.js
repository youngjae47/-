/** "YYYY-MM-DD" → 공휴일 이름 (없으면 undefined) */
function getHoliday(dateKey) {
  const [y, m, d] = dateKey.split("-");
  return HOLIDAYS[Number(y)]?.[`${m}-${d}`];
}

/** 해당 연도 공휴일 데이터가 있는지 */
function hasHolidayData(year) {
  return Boolean(HOLIDAYS[year]);
}
